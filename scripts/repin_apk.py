#!/usr/bin/env python3
"""Re-pin the Wolfi apk package versions in the Dockerfiles.

Pinning the base image by digest is *not* enough to make a build reproducible:
`apk add` resolves against the live Wolfi package repo at build time, so the
toolchain (python, pip, build-base) floats even while the digest stays fixed.
That is how a vulnerable pip once reached a "pinned" image — the buildx cache
was the only thing holding the old resolution, and a cache miss silently pulled
a newer one.

So every package the Dockerfiles install carries an explicit `name=version`
pin. This script resolves what the *current* base digest would install and
rewrites those pins to match. It is the apk analogue of `make base-digest`.

Pinning the named packages is still not the whole story for the image that
ships: `apk add python-3.14=X` pulls ~16 dependencies (expat, sqlite, the pip
wheel, …) that float just the same. The build cache then decides which version
of those a given build sees, so three identical CI jobs could disagree about
whether the image has a fixable CVE. The *runtime* stage (the last `FROM`)
therefore pins its whole transitive closure too, in a block this script owns:

    RUN apk add --no-cache \\
          python-3.14=3.14.10-r0 \\
          # apk-closure: ... (everything below is generated — do not edit)
          libexpat1=2.10.0-r1 \\
          ...

Build stages keep top-level pins only: they are discarded, never scanned, and
their closure (the whole compiler toolchain) would be noise in every diff.

The pins are refreshed together with the digest by `wolfi-base-check.yml`, so
security updates still arrive promptly — they just arrive as a reviewable diff
instead of appearing mid-build.

Usage:
    python scripts/repin_apk.py                 # rewrite pins to match the digest
    python scripts/repin_apk.py --check         # exit 1 if any pin is stale
    python scripts/repin_apk.py --digest sha256:...   # resolve against a specific base
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

DOCKERFILES = ("Dockerfile", "Dockerfile.hf", "Dockerfile.deep")
BASE_REPO = "cgr.dev/chainguard/wolfi-base"

# A pinned package on its own continuation line, e.g. "      py3.14-pip=26.2.1-r0 \".
# Keeping one package per line is what makes this rewrite line-local and safe.
PIN_RE = re.compile(
    r"^(?P<indent>\s+)(?P<name>[a-z0-9][a-z0-9._+-]*)=(?P<version>[^\s\\]+)(?P<tail>\s*\\?)$"
)

DIGEST_RE = re.compile(r"sha256:[a-f0-9]{64}")
FROM_RE = re.compile(r"^\s*FROM\s", re.IGNORECASE)
RUN_APK_RE = re.compile(r"^\s*RUN\s+apk\s+add\b")

# Everything pinned after this comment (inside a runtime-stage `apk add` block)
# is the generated transitive closure. Docker drops comment lines inside a
# continued RUN, so the marker costs nothing at build time.
CLOSURE_MARKER = (
    "# apk-closure: transitive runtime deps, generated by scripts/repin_apk.py "
    "(`make apk-pins`) — do not edit"
)
MARKER_RE = re.compile(r"^\s*#\s*apk-closure\b")

# Dumps "name=version" for every installed package. Parsing apk's own db avoids
# `apk info -v`, which prints descriptions rather than versions.
_DUMP_INSTALLED = (
    "awk -v RS='' -F'\\n' '{n=\"\";v=\"\";"
    'for(i=1;i<=NF;i++){if($i~/^P:/)n=substr($i,3);if($i~/^V:/)v=substr($i,3)}'
    ";if(n!=\"\")print n\"=\"v}' /lib/apk/db/installed"
)

# (file, package, old version or None if added, new version or None if dropped)
Change = tuple[str, str, "str | None", "str | None"]


@dataclass
class Block:
    """One `RUN apk add` instruction: its pinned lines, by line index."""

    stage: int
    top: list[tuple[int, re.Match]] = field(default_factory=list)
    marker: int | None = None
    closure: list[tuple[int, re.Match]] = field(default_factory=list)

    @property
    def names(self) -> tuple[str, ...]:
        return tuple(sorted(m["name"] for _, m in self.top))


def read_digest(root: Path) -> str:
    """The base digest currently pinned in Dockerfile."""
    text = (root / "Dockerfile").read_text()
    match = DIGEST_RE.search(text)
    if not match:
        sys.exit("error: no sha256 base digest found in Dockerfile")
    return match.group(0)


def apk_blocks(lines: list[str]) -> list[Block]:
    """Find the pinned packages inside `RUN apk add` blocks only.

    Scoping to the block matters: a bare `name=value` regex also matches LABEL
    continuation lines such as `org.opencontainers.image.licenses="Apache-2.0"`.
    """
    blocks: list[Block] = []
    stage = 0
    current: Block | None = None
    for i, line in enumerate(lines):
        stripped = line.rstrip("\n")
        if current is None:
            if FROM_RE.match(stripped):
                stage += 1
            elif RUN_APK_RE.match(stripped):
                current = Block(stage=stage)
                blocks.append(current)
        else:
            if MARKER_RE.match(stripped):
                current.marker = i
            else:
                match = PIN_RE.match(stripped)
                if match:
                    (current.top if current.marker is None else current.closure).append(
                        (i, match)
                    )
        # A comment line inside a continued RUN does not end the instruction.
        if current is not None and not stripped.lstrip().startswith("#"):
            if not stripped.rstrip().endswith("\\"):
                current = None
    return blocks


def runtime_blocks(blocks: list[Block]) -> list[Block]:
    """The `apk add` blocks of the final stage — the image that actually ships."""
    if not blocks:
        return []
    last = max(b.stage for b in blocks)
    return [b for b in blocks if b.stage == last and b.top]


def pinned_packages(root: Path) -> dict[str, set[str]]:
    """Map top-level package name -> the versions pinned across the Dockerfiles."""
    found: dict[str, set[str]] = {}
    for name in DOCKERFILES:
        lines = (root / name).read_text().splitlines()
        for block in apk_blocks(lines):
            for _, match in block.top:
                found.setdefault(match["name"], set()).add(match["version"])
    return found


def runtime_sets(root: Path) -> set[tuple[str, ...]]:
    """The distinct sets of top-level packages the runtime stages install."""
    sets: set[tuple[str, ...]] = set()
    for name in DOCKERFILES:
        lines = (root / name).read_text().splitlines()
        for block in runtime_blocks(apk_blocks(lines)):
            sets.add(block.names)
    return sets


def _run_in_base(digest: str, script: str) -> str:
    proc = subprocess.run(
        [
            "docker", "run", "--rm", "--platform", "linux/amd64",
            "--entrypoint", "sh", f"{BASE_REPO}@{digest}", "-c", script,
        ],
        capture_output=True,
        text=True,
    )
    if proc.returncode != 0:
        sys.exit(f"error: could not resolve apk versions on {digest}\n{proc.stderr}")
    return proc.stdout


def _parse_installed(text: str) -> dict[str, str]:
    return dict(line.split("=", 1) for line in text.splitlines() if "=" in line)


def resolve_versions(digest: str, packages: list[str]) -> dict[str, str]:
    """Ask the base image what `apk add <packages>` resolves to today."""
    script = (
        f"apk add --no-cache {' '.join(packages)} >/dev/null 2>&1 || exit 1\n"
        f"{_DUMP_INSTALLED}\n"
    )
    installed = _parse_installed(_run_in_base(digest, script))
    missing = [p for p in packages if p not in installed]
    if missing:
        sys.exit(f"error: not installed on the base image: {', '.join(missing)}")
    return {p: installed[p] for p in packages}


def closure_of(
    before: dict[str, str], after: dict[str, str], top: tuple[str, ...]
) -> dict[str, str]:
    """What installing `top` added to (or upgraded on) the base, minus `top`."""
    return {
        pkg: ver
        for pkg, ver in after.items()
        if before.get(pkg) != ver and pkg not in top
    }


def resolve_closure(
    digest: str, top: tuple[str, ...], versions: dict[str, str]
) -> dict[str, str]:
    """The transitive packages `apk add <top>` pulls onto the bare base image."""
    script = (
        f"{_DUMP_INSTALLED}\necho ---\n"
        f"apk add --no-cache {' '.join(top)} >/dev/null 2>&1 || exit 1\n"
        f"{_DUMP_INSTALLED}\n"
    )
    before_text, _, after_text = _run_in_base(digest, script).partition("---\n")
    before, after = _parse_installed(before_text), _parse_installed(after_text)
    # The closure is resolved in its own container, moments after the top-level
    # versions. If the repo published in between, the two disagree and the pins
    # would not install together — refuse rather than write a broken set.
    moved = [p for p in top if after.get(p) != versions.get(p)]
    if moved:
        sys.exit(
            "error: the Wolfi repo changed mid-resolution "
            f"({', '.join(moved)}); re-run"
        )
    return closure_of(before, after, top)


def rewrite_text(
    name: str,
    text: str,
    versions: dict[str, str],
    closures: dict[tuple[str, ...], dict[str, str]],
) -> tuple[str, list[Change]]:
    """Return `text` with every pin brought up to date, plus what changed."""
    lines = text.splitlines(keepends=True)
    blocks = apk_blocks([line.rstrip("\n") for line in lines])
    runtime = {id(b) for b in runtime_blocks(blocks)}
    changes: list[Change] = []

    # Bottom-up, so regenerating a closure (which changes the line count) does
    # not shift the indices of the blocks still to be processed.
    for block in reversed(blocks):
        if not block.top:
            continue
        indent = block.top[0][1]["indent"]
        pins = block.top + block.closure
        # Whatever ended the last pinned line (" \" when the RUN continues with
        # `&& ...`, nothing when it does not) must still end the last one after.
        final_tail = pins[-1][1]["tail"]

        new_top: list[str] = []
        for _, match in block.top:
            newest = versions.get(match["name"], match["version"])
            if newest != match["version"]:
                changes.append((name, match["name"], match["version"], newest))
            new_top.append(f"{indent}{match['name']}={newest}")

        new_closure: list[str] = []
        if id(block) in runtime:
            wanted = closures.get(block.names, {})
            have = {m["name"]: m["version"] for _, m in block.closure}
            for pkg in sorted(set(wanted) | set(have)):
                if wanted.get(pkg) != have.get(pkg):
                    changes.append((name, pkg, have.get(pkg), wanted.get(pkg)))
            new_closure = [f"{indent}{pkg}={ver}" for pkg, ver in sorted(wanted.items())]

        body = new_top + new_closure
        rendered = [f"{entry} \\\n" for entry in body[:-1]]
        rendered.append(f"{body[-1]}{final_tail}\n")
        if new_closure:
            rendered.insert(len(new_top), f"{indent}{CLOSURE_MARKER}\n")

        first = block.top[0][0]
        last = max([pins[-1][0]] + ([block.marker] if block.marker is not None else []))
        if not lines[last].endswith("\n"):
            rendered[-1] = rendered[-1].rstrip("\n")
        lines[first : last + 1] = rendered

    return "".join(lines), changes


def describe(change: Change) -> str:
    fname, pkg, old, new = change
    if old is None:
        return f"{fname}: {pkg} (new closure pin) -> {new}"
    if new is None:
        return f"{fname}: {pkg} {old} -> (no longer installed)"
    return f"{fname}: {pkg} {old} -> {new}"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--digest", help="base digest to resolve against")
    parser.add_argument(
        "--check",
        action="store_true",
        help="report stale pins and exit 1 without writing",
    )
    parser.add_argument("--root", default=".", help="repository root")
    args = parser.parse_args()

    root = Path(args.root)
    digest = args.digest or read_digest(root)

    pins = pinned_packages(root)
    if not pins:
        sys.exit(
            "error: no `name=version` apk pins found — expected one package per "
            "line inside the `apk add` blocks"
        )

    # A package pinned to different versions in different Dockerfiles is a bug;
    # they all build on the same base.
    for pkg, seen in sorted(pins.items()):
        if len(seen) > 1:
            print(
                f"warning: {pkg} pinned inconsistently: {', '.join(sorted(seen))}",
                file=sys.stderr,
            )

    packages = sorted(pins)
    print(f"base:     {digest}")
    print(f"packages: {', '.join(packages)}")

    versions = resolve_versions(digest, packages)
    closures = {
        top: resolve_closure(digest, top, versions) for top in sorted(runtime_sets(root))
    }
    for top, closure in closures.items():
        print(f"closure:  {', '.join(top)} -> {len(closure)} transitive packages")

    changes: list[Change] = []
    rewritten: dict[Path, str] = {}
    for name in DOCKERFILES:
        path = root / name
        new_text, file_changes = rewrite_text(name, path.read_text(), versions, closures)
        changes.extend(file_changes)
        rewritten[path] = new_text

    if args.check:
        if changes:
            print("\nstale apk pins:", file=sys.stderr)
            for change in changes:
                print(f"  {describe(change)}", file=sys.stderr)
            print("\nrun `make apk-pins` to refresh them.", file=sys.stderr)
            return 1
        print("\napk pins are current.")
        return 0

    if not changes:
        print("\napk pins already current — nothing to do.")
        return 0

    for path, new_text in rewritten.items():
        path.write_text(new_text)
    print()
    for change in changes:
        print(describe(change))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
